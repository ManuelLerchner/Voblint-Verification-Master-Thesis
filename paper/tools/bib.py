"""Extract the paper's bibliography from the thesis bibliography.

thesis/literature.bib is the one checked bibliography. The paper cites a
subset, so this script collects every key the paper's .tex files cite and
copies exactly those entries. A key missing from the thesis bibliography is
an error: add and check the entry there first.

  python paper/tools/bib.py --write   regenerate paper/generated/references.bib
  python paper/tools/bib.py --check   fail if it is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
THESIS_BIB = ROOT / "thesis" / "literature.bib"
PAPER = ROOT / "paper"
TARGET = PAPER / "generated" / "references.bib"

CITE = re.compile(r"\\cite[a-zA-Z]*\*?(?:\[[^\]]*\])*\{([^}]*)\}")
ENTRY_START = re.compile(r"^@\w+\{([^,\s]+),", re.MULTILINE)


def cited_keys() -> list[str]:
    keys: set[str] = set()
    for tex in sorted(PAPER.rglob("*.tex")):
        if "generated" in tex.parts:
            continue
        text = re.sub(r"(?<!\\)%.*", "", tex.read_text())
        for group in CITE.findall(text):
            keys.update(k.strip() for k in group.split(",") if k.strip())
    return sorted(keys)


BARE_URL = re.compile(r"(?<![{=\w])(https?://[^\s},]+?)([.,;]?)(?=[\s},])")


def latex_safe(entry: str) -> str:
    # The thesis bibliography is read by Typst, which accepts bare URLs in
    # free-text fields; BibTeX passes them to LaTeX, where `_` breaks.
    out = []
    for line in entry.split("\n"):
        field = line.strip().split("=", 1)[0].strip().lower()
        if field in ("note", "howpublished", "annote"):
            line = BARE_URL.sub(r"\\url{\1}\2", line)
        out.append(line)
    return "\n".join(out)


def entries() -> dict[str, str]:
    text = THESIS_BIB.read_text()
    starts = [(m.start(), m.group(1)) for m in ENTRY_START.finditer(text)]
    found: dict[str, str] = {}
    for i, (pos, key) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else len(text)
        found[key] = latex_safe(text[pos:end].rstrip()) + "\n"
    return found


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()

    known = entries()
    keys = cited_keys()
    missing = [k for k in keys if k not in known]
    if missing:
        print("not in thesis/literature.bib: " + ", ".join(missing), file=sys.stderr)
        return 1
    text = (
        "% generated by paper/tools/bib.py from thesis/literature.bib\n\n"
        + "\n".join(known[k] for k in keys)
    )
    if args.write:
        TARGET.parent.mkdir(exist_ok=True)
        TARGET.write_text(text)
        return 0
    if not TARGET.exists() or TARGET.read_text() != text:
        print(
            "stale paper bibliography; run paper/tools/bib.py --write", file=sys.stderr
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
