"""Expose the thesis's repository statistics to the paper as \\stat{key}.

Every thesis build writes thesis/shared/generated/stats.json from
scripts/pages_stats.py. The paper reads the same numbers, so no figure about
the repository is typed by hand. An unknown key fails the LaTeX build.

  python paper/tools/stats.py   regenerate paper/generated/stats.tex
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "thesis" / "shared" / "generated" / "stats.json"
PROFILING = ROOT / "thesis" / "shared" / "generated" / "profiling.json"
TARGET = ROOT / "paper" / "generated" / "stats.tex"


def grouped(value: int | float) -> str:
    if isinstance(value, int):
        return f"{value:,}".replace(",", "{,}")
    return f"{value:.2f}"


def flatten(prefix: str, value: object, out: dict[str, object]) -> None:
    if isinstance(value, dict):
        for key, inner in value.items():
            flatten(f"{prefix}.{key}", inner, out)
    elif isinstance(value, (int, float)) and not isinstance(value, bool):
        out[prefix] = value


def main() -> int:
    if not SOURCE.exists():
        print("missing stats.json; run pixi run thesis-draft first", file=sys.stderr)
        return 1
    stats = json.loads(SOURCE.read_text())["stats"]
    # Running-time figures the thesis evaluation reads, as prof.<path>.
    if PROFILING.exists():
        flatten("prof", json.loads(PROFILING.read_text()), stats)
    lines = [
        "% generated by paper/tools/stats.py from thesis/shared/generated/stats.json",
        r"\newcommand{\stat}[1]{\ifcsname stat:#1\endcsname\csname stat:#1\endcsname"
        r"\else\errmessage{unknown stat #1}\fi}",
    ]
    for key, value in sorted(stats.items()):
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            lines.append(
                rf"\expandafter\def\csname stat:{key}\endcsname{{{grouped(value)}}}"
            )
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
