"""Render solve cost per context policy from the committed profiling snapshot.

The snapshot pages/data/profiling/<date>-<rev>.json is what the thesis's
running-time section and the site's profiling page read. Each case is one
fixture under one configuration; its time is the median over the successful
repetitions, and a case that fails or times out once counts as failed.

  python paper/tools/costs.py   regenerate paper/generated/costs.tex
"""

from __future__ import annotations

import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SNAPSHOT = ROOT / "pages" / "data" / "profiling" / "2026-10-21-17fcb363d.json"
TARGET = ROOT / "paper" / "generated" / "costs.tex"

POLICIES = [
    ("none", "one context per procedure"),
    ("call-string-1", "call strings, length 1"),
    ("entry-state", "entry states"),
]


def quantile(values: list[float], q: float) -> float:
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, int(q * len(ordered)))]


def main() -> int:
    runs = json.loads(SNAPSHOT.read_text())["runs"]
    ok: dict[str, list[dict]] = defaultdict(list)
    timeouts: dict[str, int] = defaultdict(int)
    for run in runs:
        if run["status"] == "ok":
            ok[run["context"]].append(run)
        elif run["status"] == "timeout":
            timeouts[run["context"]] += 1
    rows = []
    for key, label in POLICIES:
        cases = ok[key]
        if not cases:
            print(f"no successful cases for {key}", file=sys.stderr)
            return 1
        ms = [c["ms"] for c in cases]
        contexts = [c["contexts"] for c in cases]
        rows.append(
            f"{label} & {len(cases) + timeouts[key]} & {timeouts[key]} & "
            f"{statistics.median(ms):.2f} & {quantile(ms, 0.95):.2f} & "
            f"{max(ms):.0f} & {max(contexts)} \\\\"
        )
    lines = [
        "% generated by paper/tools/costs.py from " + SNAPSHOT.name,
        r"\begin{tabular}{@{}lrrrrrr@{}}",
        r"\toprule",
        r"Context policy & Cases & Timeouts & Median & 95\,\% & Max & Contexts \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
    ]
    TARGET.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
