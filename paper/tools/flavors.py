"""Render the Voblint/Goblint comparison on Monniaux's flavors programs.

Voblint verdicts come from the thesis's registered claims
(thesis/shared/generated/flavors-*.txt, re-checked by `pixi run
thesis-claims`); Goblint verdicts from the recorded run in
thesis/shared/code/goblint-flavors/results.tsv. The program list and the
setting rows are those of the thesis table (13-evaluation.typ, tab:flavors).

  python paper/tools/flavors.py   regenerate paper/generated/flavors.tex
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CLAIMS = ROOT / "thesis" / "shared" / "generated"
GOBLINT = ROOT / "thesis" / "shared" / "code" / "goblint-flavors" / "results.tsv"
TARGET = ROOT / "paper" / "generated" / "flavors.tex"

# (column label, Voblint claim key, check, Goblint program)
PROGRAMS = [
    ("signs", "vanilla", "z < 0", "vanilla"),
    ("not ind.", "not-inductive", "i > 0", "sign_not_inductive"),
    ("abs.", "coffee", "x != 0", "coffee_bounded"),
    ("bounded", "fudge", "i == 10", "fudge"),
    ("reset", "reset-bound", "i <= 9", "narrow_works_lb"),
    ("reset", "reset-bound", "i >= 0", "narrow_works_lb"),
    ("skipped", "skipped", "i <= 9", "blackcurrant"),
    ("reset eq.", "reset-eq", "i <= 9", "reset_eq"),
]
VOBLINT = [
    ("Sign", "sign"),
    ("Interval", "interval"),
    ("Int", "int"),
    ("Int, Order", "int-order"),
]
GOBLINT_ROWS = [
    ("Interval", "interval"),
    ("delay 10", "interval+gas10"),
    ("Int, delay 3", "int+gas3"),
    ("thresholds", "interval+thresholds"),
    ("comparisons", "interval+thresholds-comparisons"),
    ("octagons", "octagon"),
    ("octagons, paths", "octagon+branches"),
]


def voblint_verdict(key: str, setting: str, cond: str) -> str:
    text = (CLAIMS / f"flavors-{key}-{setting}.txt").read_text()
    for line in text.splitlines():
        cells = line.split()
        joined = " ".join(cells)
        if f" {cond} " in f" {joined} " and any(
            v in cells for v in ("PROVED", "UNKNOWN", "REFUTED", "DEAD")
        ):
            return next(
                v for v in ("PROVED", "UNKNOWN", "REFUTED", "DEAD") if v in cells
            )
    raise SystemExit(f"no verdict for {cond} in flavors-{key}-{setting}")


def goblint_verdict(
    rows: dict[tuple[str, str], str], prog: str, setting: str, cond: str
) -> str:
    outs = [
        o.strip()
        for o in rows[(prog, setting)].split(";")
        if o.strip().startswith(cond + ":")
    ]
    if not outs:
        raise SystemExit(f"no Goblint result for {cond} in {prog}/{setting}")
    return "PROVED" if all(o.endswith("will succeed") for o in outs) else "UNKNOWN"


def cell(verdict: str) -> str:
    return r"\checkmark" if verdict == "PROVED" else r"--"


def main() -> int:
    rows = {}
    for line in GOBLINT.read_text().splitlines():
        parts = line.split("\t")
        if len(parts) == 3:
            rows[(parts[0], parts[1])] = parts[2]
    out = [
        "% generated by paper/tools/flavors.py",
        r"\begin{tabular}{ll" + "c" * len(PROGRAMS) + "}",
        r"\toprule",
        " & & " + " & ".join(label for label, *_ in PROGRAMS) + r" \\",
        " & & "
        + " & ".join(r"\texttt{" + cond + "}" for _, _, cond, _ in PROGRAMS)
        + r" \\",
        r"\midrule",
    ]
    for i, (name, setting) in enumerate(VOBLINT):
        lead = r"\multirow{4}{*}{Voblint}" if i == 0 else ""
        cells = [
            cell(voblint_verdict(key, setting, cond)) for _, key, cond, _ in PROGRAMS
        ]
        out.append(f"{lead} & {name} & " + " & ".join(cells) + r" \\")
    out.append(r"\midrule")
    for i, (name, setting) in enumerate(GOBLINT_ROWS):
        lead = r"\multirow{7}{*}{Goblint}" if i == 0 else ""
        cells = [
            cell(goblint_verdict(rows, prog, setting, cond))
            for _, _, cond, prog in PROGRAMS
        ]
        out.append(f"{lead} & {name} & " + " & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    TARGET.write_text("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
