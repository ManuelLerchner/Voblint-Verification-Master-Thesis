"""Render the thesis's extracted Isabelle snippets as LaTeX for the paper.

The thesis extracts declarations and theorem statements verbatim from the
theories (thesis/shared/generated/snippets, kept current by
`pixi run thesis-snippets`). The paper reuses them instead of retyping, and
typesets them with Isabelle's own isabelle.sty / isabellesym.sty macros so a
symbol renders as Isabelle's document preparation would render it.

  python paper/tools/snippets.py --write   regenerate paper/generated/*.tex
  python paper/tools/snippets.py --check   fail if any generated file is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "thesis" / "shared" / "generated" / "snippets"
TARGET = ROOT / "paper" / "generated"
LIST = ROOT / "paper" / "snippets.txt"

COMMANDS = {
    "theorem",
    "lemma",
    "corollary",
    "locale",
    "definition",
    "abbreviation",
    "datatype",
    "inductive",
    "inductive_set",
    "type_synonym",
    "fun",
    "function",
}
KEYWORDS = {"fixes", "assumes", "shows", "defines", "and", "where", "for", "obtains"}

CHAR_MACROS = {
    "_": r"\isacharunderscore{}",
    "{": r"\isacharbraceleft{}",
    "}": r"\isacharbraceright{}",
    "#": r"\isacharhash{}",
    "$": r"\isachardollar{}",
    "%": r"\isacharpercent{}",
    "&": r"\isacharampersand{}",
    "~": r"\isachartilde{}",
    "^": r"\isacharcircum{}",
    "\\": r"\isacharbackslash{}",
    "'": r"\isacharprime{}",
    '"': r"\isachardoublequote{}",
    "(": r"\isacharparenleft{}",
    ")": r"\isacharparenright{}",
    "[": r"\isacharbrackleft{}",
    "]": r"\isacharbrackright{}",
    "<": r"\isacharless{}",
    ">": r"\isachargreater{}",
    "|": r"\isacharbar{}",
    "@": r"\isacharat{}",
    ",": r"\isacharcomma{}",
    ":": r"\isacharcolon{}",
    ";": r"\isacharsemicolon{}",
    "=": r"\isacharequal{}",
    "-": r"\isacharminus{}",
    "+": r"\isacharplus{}",
    "*": r"\isacharasterisk{}",
    ".": r"\isachardot{}",
    "/": r"\isacharslash{}",
    "?": r"\isacharquery{}",
    "!": r"\isacharbang{}",
    "`": r"\isacharbackquote{}",
}

TOKEN = re.compile(
    r"\\<\^(?P<ctrl>[a-z]+)>|\\<(?P<sym>[A-Za-z][A-Za-z0-9]*)>|(?P<word>[A-Za-z0-9_']+)|(?P<other>.)"
)


def render_symbol(tok: re.Match[str]) -> str:
    return "{\\isasym" + tok.group("sym") + "}"


def render_line(line: str) -> str:
    out: list[str] = []
    pending_script: str | None = None
    indent = len(line) - len(line.lstrip(" "))
    if indent:
        out.append("\\isaindent{" + "\\ " * indent + "}")
    first_word = True
    for tok in TOKEN.finditer(line[indent:]):
        if tok.group("ctrl"):
            ctrl = tok.group("ctrl")
            if ctrl in ("sub", "sup"):
                pending_script = ctrl
                continue
            out.append(
                "\\isactrl" + ctrl + "{}"
                if ctrl.startswith("e")
                else "\\isactrl" + ctrl + " "
            )
            continue
        if tok.group("sym"):
            piece = render_symbol(tok)
        elif tok.group("word"):
            word = tok.group("word")
            if pending_script:
                # \<^sub>x scripts exactly one following character.
                head, word = word[0], word[1:]
                out.append("\\isactrl" + pending_script + "{" + head + "}")
                pending_script = None
                if not word:
                    continue
            escaped = "".join(CHAR_MACROS.get(c, c) for c in word)
            if first_word and word in COMMANDS:
                piece = "\\isacommand{" + escaped + "}"
            elif word in KEYWORDS:
                piece = "\\isakeyword{" + escaped + "}"
            else:
                piece = escaped
            first_word = False
        else:
            ch = tok.group("other")
            piece = "\\ " if ch == " " else CHAR_MACROS.get(ch, ch)
        if pending_script:
            out.append("\\isactrl" + pending_script + "{" + piece + "}")
            pending_script = None
        else:
            out.append(piece)
    return "".join(out)


def render(name: str) -> str:
    lines = (SOURCE / f"{name}.thy").read_text().rstrip("\n").split("\n")
    origin = lines[0].strip() if lines and lines[0].startswith("(*") else ""
    body = lines[1:] if origin else lines
    rendered = "\\isanewline\n".join(render_line(line) for line in body)
    header = f"% generated by paper/tools/snippets.py from {name}.thy {origin}\n"
    return header + "\\begin{isabelle}\n" + rendered + "\n\\end{isabelle}\n"


def names() -> list[str]:
    return [
        n.strip()
        for n in LIST.read_text().splitlines()
        if n.strip() and not n.startswith("#")
    ]


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()

    stale: list[str] = []
    TARGET.mkdir(exist_ok=True)
    for name in names():
        if not (SOURCE / f"{name}.thy").exists():
            print(
                f"missing thesis snippet {name}; add it to thesis/shared/snippets.toml",
                file=sys.stderr,
            )
            return 1
        text = render(name)
        path = TARGET / f"{name}.tex"
        if args.write:
            path.write_text(text)
        elif not path.exists() or path.read_text() != text:
            stale.append(name)
    if stale:
        print(
            "stale paper snippets: "
            + ", ".join(stale)
            + "; run paper/tools/snippets.py --write",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
