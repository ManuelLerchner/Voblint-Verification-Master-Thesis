"""Render the per-layer size table of the mechanization.

Reads the same measurement as the site and the thesis (scripts/pages_stats.py,
which counts the theories each session lists), grouped by top-level source
directory, plus the part of the vendored solver Voblint imports.

  pixi run python3 paper/tools/scale.py   regenerate paper/generated/scale.tex
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

import pages_stats  # noqa: E402

TARGET = ROOT / "paper" / "generated" / "scale.tex"

# Reading order of the paper, with the role each layer plays in it.
LAYERS = [
    ("Program_Model", "source semantics, CFG, compiler, traces, contract"),
    (
        "Abstract_Interpreter",
        "domain interfaces, D/G framework, routing, solver bridge",
    ),
    ("Analyses", "Sign, Interval, Parity, Congruence, Int, relational witness"),
    ("Executable_Surface", "analyzer function, report, end-to-end theorems, export"),
    ("Examples", "non-vacuity, precision witnesses, regressions"),
]


def grouped(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def main() -> int:
    stats = pages_stats.collect()
    areas = {a["name"]: a for a in stats["isabelle"]["sessions"]}
    missing = [name for name, _ in LAYERS if name not in areas]
    if missing:
        print("unknown layers: " + ", ".join(missing), file=sys.stderr)
        return 1
    rows = []
    for name, role in LAYERS:
        a = areas[name]
        label = name.replace("_", r"\_")
        rows.append(
            rf"\texttt{{{label}}} & {role} & {a['theories']} & "
            rf"{grouped(a['lines'])} & {grouped(a['proofs'])} \\"
        )
    used = stats["solver"]["used"]
    total = stats["isabelle"]
    lines = [
        "% generated by paper/tools/scale.py from scripts/pages_stats.py",
        r"\begin{tabular}{@{}lp{0.4\textwidth}rrr@{}}",
        r"\toprule",
        r"Layer & Contents & Theories & Lines & Proved \\",
        r"\midrule",
        *rows,
        r"\midrule",
        rf"Voblint total & & {total['theories']} & {grouped(total['lines'])} & "
        rf"{grouped(total['proofs'])} \\",
        rf"Solver (imported) & Tilscher et al.~\cite{{tilscher26}} & {used['theories']} & "
        rf"{grouped(used['lines'])} & {grouped(used['proofs'])} \\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    TARGET.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
