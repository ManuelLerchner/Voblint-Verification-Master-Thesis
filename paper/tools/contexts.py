"""Render the context-policy comparison of the evaluation.

Reads the registered claims ctx-mutual-* and ctx-mutual-*-dot
(thesis/shared/claims.toml), whose
outputs `pixi run thesis-claims` re-checks against the analyzer.

  python paper/tools/contexts.py   regenerate paper/generated/contexts.tex
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CLAIMS = ROOT / "thesis" / "shared" / "generated"
TARGET = ROOT / "paper" / "generated" / "contexts.tex"

POLICIES = [
    ("none", "one context per procedure"),
    ("k1", "call strings, length 1"),
    ("k2", "call strings, length 2"),
    ("entry", "entry states"),
]
CHECKS = ["res1 == 2", "res2 == 1"]
VERDICTS = ("PROVED", "UNKNOWN", "REFUTED", "DEAD")


def check_row(claim: str, cond: str) -> tuple[str, str]:
    for line in (CLAIMS / f"{claim}.txt").read_text().splitlines():
        cells = line.split()
        if f" {cond} " in f" {' '.join(cells)} ":
            verdict = next(v for v in VERDICTS if v in cells)
            state = line.split("interval:", 1)[1].strip()
            return verdict, state.split("=", 1)[1]
    raise SystemExit(f"no check {cond} in {claim}")


def callee_contexts(key: str) -> int:
    """Copies of f and g in the solved graph: one cluster per procedure and context."""
    dot = (CLAIMS / f"ctx-mutual-{key}-dot.txt").read_text()
    return len(set(re.findall(r'label="[fg] / [^"]*"', dot)))


def main() -> int:
    rows = []
    for key, label in POLICIES:
        cells = [str(callee_contexts(key))]
        for cond in CHECKS:
            verdict, value = check_row(f"ctx-mutual-{key}", cond)
            value = value.replace("∞", r"\infty")
            cells.append(rf"\verdict{{{verdict}}} & ${value}$")
        rows.append(f"{label} & " + " & ".join(cells) + r" \\")
    lines = [
        "% generated by paper/tools/contexts.py from the ctx-mutual-* claims",
        r"\begin{tabular}{@{}lrllll@{}}",
        r"\toprule",
        r"Context policy & Contexts & \multicolumn{2}{l}{\texttt{res1 == 2}} & "
        r"\multicolumn{2}{l}{\texttt{res2 == 1}} \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
    ]
    TARGET.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
