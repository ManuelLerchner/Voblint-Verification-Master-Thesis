#!/usr/bin/env python3
"""Generates the VIMP frontend -- a Menhir parser (vimp_parser.mly) and a
real ocamllex lexer (vimp_lexer.mll) -- from the canonical manifests/vimp-grammar.yaml.

This is the source of cli/frontend/vimp_parser.mly and cli/frontend/vimp_lexer.mll. The
generated .mly/.mll are committed, the same convention codegen/generated/
already uses for Isabelle-generated sources: `pixi run cli-build`
(scripts/mk/cli-build.sh) needs only Dune/Menhir/ocamllex, not Python,
extending its "does not require Isabelle" framing to "does not require
regenerating the frontend either, unless manifests/vimp-grammar.yaml changed."

Requires PyYAML to regenerate (`pip install pyyaml`, or `pixi install` from
the repo root already has it) -- not to build.

Usage: python3 scripts/gen_vimp_menhir.py [manifests/vimp-grammar.yaml] [out_dir]
"""

import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_GRAMMAR = REPO_ROOT / "manifests" / "vimp-grammar.yaml"
DEFAULT_OUT = REPO_ROOT / "cli" / "frontend"

HEADER = (
    "(* GENERATED by scripts/gen_vimp_menhir.py from manifests/vimp-grammar.yaml. "
    "Do not hand-edit; regenerate instead. *)\n"
)

# -- `special: name` productions, keyed by that name (not by production
# name -- manifests/vimp-grammar.yaml's header comment explains what each covers). ---
SPECIAL_ACTIONS = {
    "integer_literal": "Voblint.N (Voblint.Int_of_integer v0)",
    "unary_minus": """\
match v1 with
      | Voblint.N (Voblint.Int_of_integer z) ->
        Voblint.N (Voblint.Int_of_integer (Z.neg z))
      | _ ->
        Voblint.Minus
          (Voblint.N (Voblint.Int_of_integer Z.zero), v1)""",
}


# -- `lower: {ctor: ..., args: [...]}` / `lower: {tuple: [...]}` renderer --


def render_lower_arg(arg: dict) -> str:
    if "ctor" in arg:
        value = render_lower(arg)
        if owns_stmt_index({"lower": arg}):
            return f"(record_stmt_pos $endpos $endpos ({value}))"
        return f"({value})"
    if "rhs" in arg:
        return f"v{arg['rhs']}"
    if "some" in arg:
        return f"(Some {render_lower_arg(arg['some'])})"
    if "none" in arg:
        return "None"
    if "literal" in arg:
        return "true" if arg["literal"] else "false"
    if "int" in arg:
        return f"(Voblint.Int_of_integer (Z.of_int {arg['int']}))"
    if "source_label" in arg:
        return "(source_label $startpos)"
    raise ValueError(f"unrecognized lower arg shape: {arg}")


# Commands the parser builds carry the unit annotation; elaboration assigns
# locations only inside the proof. Seq carries none.
ANNOTATED_CTORS = {"SKIP", "Assign", "Check", "If", "While", "Call", "Return"}


def render_lower(lower: dict) -> str:
    if "tuple" in lower:
        return "(" + ", ".join(f"v{i}" for i in lower["tuple"]) + ")"
    ctor = f"Voblint.{lower['ctor']}"
    args = [render_lower_arg(a) for a in lower.get("args", [])]
    if lower["ctor"].split(".")[-1] in ANNOTATED_CTORS:
        args = ["()"] + args
    if not args:
        return ctor
    if len(args) == 1:
        return f"{ctor} {args[0]}"
    return f"{ctor} (" + ", ".join(args) + ")"


def render_action(prod: dict) -> str:
    """Renders exactly one of a production's three possible AST-construction
    shapes -- see manifests/vimp-grammar.yaml's header comment for what each covers."""
    special = prod.get("special")
    if special:
        return SPECIAL_ACTIONS[special]
    if "passthrough" in prod:
        return f"v{prod['passthrough']}"
    return render_lower(prod["lower"])


# ---------------------------------------------------------------------------
# Lexer generation: real ocamllex (.mll). manifests/vimp-grammar.yaml only describes
# the language (keywords/punctuation tables, terminal lex patterns); this
# function is where those become ocamllex's own regex/rule idiom -- not
# something the schema should encode itself (its `lex:` fields are plain
# regex-ish strings, not ocamllex character-class syntax).
# ---------------------------------------------------------------------------


def gen_lexer_mll(g: dict) -> str:
    # Keyword rules must precede the generic ident rule: ocamllex resolves
    # an exact-length tie (e.g. input "global" matches both the "global"
    # literal and ident_start ident_char*) by earliest rule, not longest
    # match beyond length -- so without this order every keyword would
    # lex as a plain IDENT instead.
    keyword_rules = "\n".join(
        f'  | "{word}"' + " " * max(1, 18 - len(word)) + f"{{ {tok} }}"
        for word, tok in g["keywords"].items()
    )
    punct_rules = "\n".join(
        f'  | "{op}"' + " " * max(1, 18 - len(op)) + f"{{ {tok} }}"
        for op, tok in g["punctuation"].items()
    )

    return (
        HEADER
        + f"""{{
open Vimp_parser

exception Lex_error of {{ line : int; col : int; msg : string }}

let error lexbuf msg =
  let pos = Lexing.lexeme_start_p lexbuf in
  raise (Lex_error {{ line = pos.Lexing.pos_lnum; col = pos.Lexing.pos_cnum - pos.Lexing.pos_bol + 1; msg }})
}}

let digit = ['0'-'9']
let ident_start = ['a'-'z' 'A'-'Z' '_']
let ident_char = ident_start | digit

rule token = parse
  | [' ' '\\t' '\\r']  {{ token lexbuf }}
  | '\\n'              {{ Lexing.new_line lexbuf; token lexbuf }}
  | "//" [^ '\\n']*    {{ token lexbuf }}
{keyword_rules}
{punct_rules}
  | ident_start ident_char* as s  {{ IDENT s }}
  | digit+ as s                   {{ INT (Z.of_string s) }}
  | eof                           {{ EOF }}
  | _ as c  {{ error lexbuf (Printf.sprintf "unexpected character %C" c) }}
"""
    )


# ---------------------------------------------------------------------------
# Parser generation
# ---------------------------------------------------------------------------

# Explicit %type declarations keep the generated interface stable across
# Dune/Menhir versions; every nonterminal's OCaml type is stated upfront.
NONTERMINAL_TYPES = {
    "exp": "Voblint.exp",
    "stmt": "(unit, string, Voblint.exp) Voblint.gcom",
    "if_stmt": "(unit, string, Voblint.exp) Voblint.gcom",
    "stmts": "(unit, string, Voblint.exp) Voblint.gcom",
    "stmts_opt": "(unit, string, Voblint.exp) Voblint.gcom",
    "actuals": "Voblint.exp list",
    "ids": "string list",
    "kind": "Voblint.ikind",
    "global_line": "Vimp_typing.global_line",
    "global_line_star": "Vimp_typing.global_line list",
    "tformal": "Vimp_typing.formal",
    "tformals": "Vimp_typing.formal list",
    "init_decl": "string * (unit, string, Voblint.exp) Voblint.gcom",
    "init_decls": "(string * (unit, string, Voblint.exp) Voblint.gcom) list",
    "local_decl": "(string * Voblint.ikind * (unit, string, Voblint.exp) Voblint.gcom) list",
    "local_decl_star": "(string * Voblint.ikind * (unit, string, Voblint.exp) Voblint.gcom) list",
    "function_decl": "Vimp_typing.definition",
    "function_decl_star": "Vimp_typing.definition list",
}


def type_decls() -> str:
    return "\n".join(f"%type <{t}> {name}" for name, t in NONTERMINAL_TYPES.items())


def token_decls(g: dict) -> str:
    names = list(g["keywords"].values()) + list(g["punctuation"].values()) + ["EOF"]
    lines = ["%token <string> IDENT", "%token <Z.t> INT"]
    lines += [f"%token {n}" for n in names]
    return "\n".join(lines)


def precedence_decls(g: dict) -> str:
    lines = []
    for level in g["precedence"]:
        assoc = {"left": "%left", "right": "%right", "none": "%nonassoc"}[
            level["assoc"]
        ]
        lines.append(f"{assoc} {' '.join(level['tokens'])}")
    return "\n".join(lines)


def binder(i: int, sym: str) -> str:
    """Menhir binder for rhs position i (symbol name sym), e.g. `v2 = exp`."""
    return f"v{i} = {sym}"


def rhs_pattern(rhs: list) -> str:
    return " ".join(binder(i, sym) for i, sym in enumerate(rhs))


# Productions whose `com` node owns a Statement index in the compiled CFG --
# exactly the clauses csize charges one for. Seq is absent on purpose: it is
# folded by the stmts list rule and allocates nothing of its own.
def owns_stmt_index(prod: dict) -> bool:
    ctor = (prod.get("lower") or {}).get("ctor")
    return ctor in {
        "SKIP",
        "Assign",
        "Check",
        "If",
        "While",
        "Return",
        "Restore",
        "Unwind",
        "com.Call",
        "com.If",
    } or ctor in {"Call"}


def render_alt(prod: dict) -> str:
    pattern = rhs_pattern(prod["rhs"])
    # A prefix form whose rightmost terminal carries no level of its own (unary
    # minus, a cast's closing parenthesis) states its level explicitly.
    is_uminus = prod.get("special") == "unary_minus" or prod.get("name") == "exp_cast"
    # Only uminus needs an explicit %prec override: every other rule's own
    # operator token (PLUS/STAR/AND/...) already sits at the end of its rhs,
    # so Menhir's default "rightmost terminal" rule picks the right level
    # automatically. Uminus's only terminal (MINUS) already carries the
    # *binary* Plus/Minus precedence, which would be wrong (too loose) here.
    prec = f" %prec {prod['precedence']}" if is_uminus else ""
    action = render_action(prod)
    # A command's own source position, recorded where the parser knows it is
    # building a command -- the lexer cannot tell a statement-position IDENT
    # from one inside an expression. Reductions are bottom-up, so these arrive
    # in post-order over the command tree; cli/frontend/vimp_frontend.ml pairs them by
    # walking the parsed AST the same way rather than assuming token order.
    if owns_stmt_index(prod):
        action = f"record_stmt_pos $startpos $endpos ({action})"
    return f"  | {pattern}{prec}\n      {{ {action} }}"


def gen_list_rule(prod: dict) -> str:
    name = prod["name"]
    item = prod.get("list_of") or prod.get("optional_list_of")
    is_optional = "optional_list_of" in prod
    ctor = prod.get("constructor")
    min_count = prod.get("min", 0)

    if is_optional:
        # `stmts_opt`: empty body folds to `empty:`, otherwise defer to the
        # already-generated non-optional list nonterminal (`stmts`).
        base = prod["result"].removesuffix("_opt")
        empty = prod.get("empty", "[]")
        empty_action = f"Voblint.{empty}" if empty[0].isupper() else empty
        if empty in ANNOTATED_CTORS:
            empty_action = f"{empty_action} ()"
        return (
            f"{name}:\n"
            f"  | (* empty *)\n"
            f"      {{ record_stmt_pos $startpos $endpos ({empty_action}) }}\n"
            f"  | cs = {base}\n"
            f"      {{ cs }}"
        )

    if ctor:
        # Left fold via a binary constructor (e.g. Seq), matching the
        # source grammar's own left-recursive `stmts_seq` shape exactly --
        # no separate associativity declaration needed, this is naturally
        # unambiguous LR: each item consumes its own closing punctuation.
        single = f"  | x = {item}\n      {{ x }}"
        multi = f"  | xs = {name} {prod.get('separator', '')} x = {item}\n      {{ Voblint.{ctor} (xs, x) }}"
        return f"{name}:\n{single}\n{multi}"

    # Plain growing list (actuals/formals/ids).
    alts = []
    if min_count == 0:
        alts.append("  | (* empty *)\n      { [] }")
    alts.append(f"  | x = {item}\n      {{ [x] }}")
    alts.append(
        f"  | xs = {name} {prod.get('separator', '')} x = {item}\n      {{ xs @ [x] }}"
    )
    return f"{name}:\n" + "\n".join(alts)


def gen_program_rule() -> str:
    # Declarations are the one part of the surface syntax the Isabelle
    # notation does not share: kinds reach a theory as `typed_prog p ds`, not
    # through `program { ... }`. Every function parses uniformly via
    # function_decl*; Vimp_typing.program picks out "main" by string equality,
    # matching VIMP_Notation.thy's prog_tr, and decides whether the program is
    # typed. See manifests/vimp-grammar.yaml's header comment on why "main" stays
    # a parse-time diagnostic rather than a deferred well-formedness check.
    return """program:
  | gs = global_line_star fs = function_decl_star EOF
      { Vimp_typing.program gs fs }

global_line_star:
  | (* empty *)
      { [] }
  | g = global_line gs = global_line_star
      { g :: gs }

global_line:
  | GLOBAL xs = ids SEMI
      { (xs, None) }
  | GLOBAL k = kind xs = ids SEMI
      { (xs, Some k) }

tformal:
  | x = IDENT
      { (x, None) }
  | k = kind x = IDENT
      { (x, Some k) }

tformals:
  | (* empty *)
      { [] }
  | f = tformal
      { [f] }
  | fs = tformals COMMA f = tformal
      { fs @ [f] }

(* A local declaration starts its variable at an arbitrary value of its kind,
   written out as a library call so the semantics, not the parser, says what
   that value may be. An initializer, as in C's `i8 x = 2;`, is an assignment
   instead, converted to the variable's kind as any assignment is. Each
   declarator is one statement at its own position. *)
init_decl:
  | x = IDENT
      { (x,
         record_stmt_pos $startpos $endpos
           (Voblint.Call ((), Some x, "__voblint_nondet_int", []))) }
  | x = IDENT ASSIGN e = exp
      { (x, record_stmt_pos $startpos $endpos (Voblint.Assign ((), x, e))) }

init_decls:
  | d = init_decl
      { [d] }
  | ds = init_decls COMMA d = init_decl
      { ds @ [d] }

local_decl:
  | k = kind ds = init_decls SEMI
      { List.map (fun (x, c) -> (x, k, c)) ds }

local_decl_star:
  | (* empty *)
      { [] }
  | l = local_decl ls = local_decl_star
      { l @ ls }

(* Locals are declared before the first statement, as CIL's fundec.slocals
   lists them, so every local is in scope throughout its procedure. *)
function_decl:
  | FUN rk = option(kind) name = IDENT LPAREN fs = tformals rp = RPAREN
    LBRACE ls = local_decl_star b = stmts_opt RBRACE
      { let body = List.fold_right (fun (_, _, c) acc -> Voblint.Seq (c, acc)) ls b in
        close_definition $startpos $endpos(rp)
          (name, fs, rk, List.map (fun (x, k, _) -> (x, k)) ls, body) }

function_decl_star:
  | (* empty *)
      { [] }
  | f = function_decl fs = function_decl_star
      { f :: fs }"""


def gen_parser(g: dict) -> str:
    productions = g["productions"]
    list_prods, regular_by_result = [], {}
    for p in productions:
        if p["name"] == "formals":
            pass  # the CLI reads typed formals (tformals, in gen_program_rule)
        elif p.get("list_of") or p.get("optional_list_of"):
            list_prods.append(p)
        elif p.get("special") == "program_structure":
            pass  # hardcoded via gen_program_rule
        elif p["result"] in ("globals", "function"):
            pass  # single-production nonterminals, emitted directly below
        else:
            regular_by_result.setdefault(p["result"], []).append(p)

    rule_blocks = []
    for result, prods in regular_by_result.items():
        alts = "\n".join(render_alt(p) for p in prods)
        rule_blocks.append(f"{result}:\n{alts}")

    for p in list_prods:
        rule_blocks.append(gen_list_rule(p))

    rule_blocks.append(gen_program_rule())

    return (
        HEADER
        + f"""
%{{
(* Menhir does not export prelude bindings through the generated .mli, so the
   recorder itself lives in cli/frontend/vimp_positions.ml where Vimp_frontend can
   reach it too. See that module for why positions are taken here rather than
   from the token stream, and what order they come out in. *)
let record_stmt_pos = Vimp_positions.record

(* A check's label is where its keyword starts, so the analysis result names
   each check by its own source position. *)
let source_label p =
  let line, column = Vimp_positions.label p in
  ( Voblint.nat_of_integer (Z.of_int line),
    Voblint.nat_of_integer (Z.of_int column) )

(* A function_decl's action builds its Vimp_typing.definition; closing the
   bucket here keeps the name, its header and its positions together without a
   second traversal. *)
let close_definition header_start header_end ((name, _, _, _, _) as decl) =
  Vimp_positions.close name header_start header_end;
  decl
%}}

{token_decls(g)}

{precedence_decls(g)}

{type_decls()}

%start <unit Voblint.imp_prog_ext> program
%%

{chr(10).join("(* " + b.split(chr(10))[0] + " *)" + chr(10) + b for b in rule_blocks)}
"""
    )


def main():
    grammar_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_GRAMMAR
    out_dir = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUT
    out_dir.mkdir(parents=True, exist_ok=True)
    g = yaml.safe_load(grammar_path.read_text())
    (out_dir / "vimp_lexer.mll").write_text(gen_lexer_mll(g))
    (out_dir / "vimp_parser.mly").write_text(gen_parser(g))
    print(f"wrote {out_dir / 'vimp_lexer.mll'}")
    print(f"wrote {out_dir / 'vimp_parser.mly'}")


if __name__ == "__main__":
    main()
